// 料理Lv1の基本エナジー = 食材エナジーの合計 × (1 + レシピボーナス)
export function baseEnergy(ings, bonus) {
  const sum = ings.reduce((p, [n, c]) => p + (INGREDIENT_ENERGY[n] || 0) * c, 0);
  return Math.round(sum * (1 + (bonus || 0) / 100));
}

